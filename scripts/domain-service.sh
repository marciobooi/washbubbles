#!/bin/bash
# Hetzner: puts a shop's own site address online (cron, every minute, see /etc/cron.d/washbubbles-domains).
# The application NEVER runs commands: it only writes a request in the database (tenant.domainState.state = pending_cert, set
# by backend/src/services/domainWatcher.js once the customer's DNS points at this server). This script, on the host, reads those
# requests, accepts only strictly formatted names, writes an nginx server block, asks Let's Encrypt for the certificate and
# marks the shop "active" (or "failed" with the reason; at most 5 attempts, to stay far from the Let's Encrypt limits).
set -u
APP=/opt/washbubbles
cd "$APP" || exit 1
HOST_RE='^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,24}$'
SLUG_RE='^[a-z0-9]([a-z0-9-]{0,38}[a-z0-9])?$'
ID_RE='^[0-9a-f]{24}$'
SERVER_IP="${SERVER_PUBLIC_IP:-128.140.118.209}"
log() { echo "[$(date '+%F %T')] $*"; }
# With MONGO_AUTH=--auth the database asks for a user: the administrator's is in .env.docker (MONGO_ROOT_USER / MONGO_ROOT_PASS).
MU=$(grep -s '^MONGO_ROOT_USER=' .env.docker | cut -d= -f2-); MP=$(grep -s '^MONGO_ROOT_PASS=' .env.docker | cut -d= -f2-)
AUTH=""; [ -n "$MU" ] && AUTH="--username $MU --password $MP --authenticationDatabase admin"
mongo() { docker compose --env-file .env.docker exec -T mongo mongosh $AUTH --quiet washstore --eval "$1"; }
setstate() { # id state message [attempts increment]
  local msg="${3//\'/ }"
  mongo "db.tenants.updateOne({_id:ObjectId('$1')},{\$set:{'domainState.state':'$2','domainState.message':'$msg','domainState.checkedAt':new Date()},\$inc:{'domainState.attempts':${4:-0}}})" > /dev/null
}

# 1. addresses that were removed from a shop (or whose shop is gone): take the nginx block down
for f in /etc/nginx/sites-enabled/store-*; do
  [ -e "$f" ] || continue
  slug="${f##*/store-}"
  [[ "$slug" =~ $SLUG_RE ]] || continue
  n=$(mongo "db.tenants.countDocuments({slug:'$slug','domains.0':{\$exists:true}})" | tr -d '[:space:]')
  if [ "$n" = "0" ]; then
    log "removing the site of '$slug' (no address any more)"
    rm -f "/etc/nginx/sites-enabled/store-$slug" "/etc/nginx/sites-available/store-$slug"
    nginx -t >/dev/null 2>&1 && systemctl reload nginx
    certbot delete --cert-name "store-$slug" --non-interactive >/dev/null 2>&1
  fi
done

# 2. shops waiting for their certificate
lines=$(mongo 'db.tenants.find({"domainState.state":"pending_cert","domainState.attempts":{$not:{$gte:5}}}).forEach(t=>print(t._id+"|"+t.slug+"|"+t.domains.join(",")))')
[ -z "$lines" ] && exit 0
while IFS='|' read -r id slug doms; do
  [ -z "$id" ] && continue
  if ! [[ "$id" =~ $ID_RE ]] || ! [[ "$slug" =~ $SLUG_RE ]]; then log "refused a malformed request ($id)"; continue; fi
  names=(); ok=1
  IFS=',' read -ra arr <<< "$doms"
  for d in "${arr[@]}"; do
    if [[ "$d" =~ $HOST_RE ]]; then names+=("$d"); else ok=0; fi
  done
  if [ "$ok" = 0 ] || [ "${#names[@]}" = 0 ]; then setstate "$id" failed "Endereço com formato inválido" 5; continue; fi
  # never touch a name another shop's block already uses
  clash=0
  for d in "${names[@]}"; do
    if grep -rlE "server_name[^;]*[[:space:]]$d[[:space:];]" /etc/nginx/sites-enabled /etc/nginx/conf.d 2>/dev/null | grep -qv "store-$slug"; then clash=1; fi
  done
  if [ "$clash" = 1 ]; then setstate "$id" failed "O endereço já está em uso noutro site deste servidor" 5; continue; fi
  # DNS again, straight from a public resolver (a cache on this host must not lie)
  for d in "${names[@]}"; do
    a=$(dig +short A "$d" @1.1.1.1 | tr '\n' ' '); aaaa=$(dig +short AAAA "$d" @1.1.1.1 | tr -d '[:space:]')
    if [ "$(echo $a)" != "$SERVER_IP" ] || [ -n "$aaaa" ]; then log "$slug: DNS of $d not right yet ($a $aaaa)"; setstate "$id" pending_dns "O DNS de $d ainda não aponta só para o nosso servidor" 0; continue 2; fi
  done
  log "$slug: DNS ok, creating the site for ${names[*]}"
  conf="/etc/nginx/sites-available/store-$slug"
  cat > "$conf" <<NGINX
# generated by scripts/domain-service.sh for the shop '$slug' - do not edit
server {
    listen 80;
    listen [::]:80;
    server_name ${names[*]};
    client_max_body_size 10m;
    location / {
        proxy_pass http://127.0.0.1:8081;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$connection_upgrade;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
NGINX
  ln -sf "$conf" "/etc/nginx/sites-enabled/store-$slug"
  if ! nginx -t >/dev/null 2>&1; then
    rm -f "/etc/nginx/sites-enabled/store-$slug" "$conf"; setstate "$id" failed "Erro interno de configuração (nginx)" 1; log "$slug: nginx -t failed, block removed"; continue
  fi
  systemctl reload nginx
  cargs=(); for d in "${names[@]}"; do cargs+=(-d "$d"); done
  if out=$(certbot --nginx "${cargs[@]}" --cert-name "store-$slug" --non-interactive --agree-tos --redirect 2>&1); then
    nginx -t >/dev/null 2>&1 && systemctl reload nginx
    if curl -fsS -o /dev/null --max-time 20 --resolve "${names[0]}:443:127.0.0.1" "https://${names[0]}/api/health"; then
      mongo "db.tenants.updateOne({_id:ObjectId('$id')},{\$set:{'domainState.state':'active','domainState.message':'','domainState.checkedAt':new Date(),'domainState.activatedAt':new Date()}})" > /dev/null
      log "$slug: ACTIVE (${names[*]})"
    else
      setstate "$id" failed "O certificado foi criado mas o site não respondeu" 1; log "$slug: certificate ok but the site did not answer"
    fi
  else
    reason=$(echo "$out" | tail -3 | tr '\n' ' ' | cut -c1-200)
    # a failed attempt must not leave a half-made block behind
    rm -f "/etc/nginx/sites-enabled/store-$slug" "$conf"; nginx -t >/dev/null 2>&1 && systemctl reload nginx
    setstate "$id" failed "Certificado: $reason" 1; log "$slug: certbot failed: $reason"
  fi
done <<< "$lines"
